export const EOTF_ITEM_COMPONENT_COUNT = 185;
export const EOTF_SKILL_COMPONENT_COUNT = 270;

export function assertEotfComponentCounts(): void {
  if (EOTF_ITEM_COMPONENTS.size !== EOTF_ITEM_COMPONENT_COUNT) {
    throw new Error(
      `EotF item component contract count drift: expected ${EOTF_ITEM_COMPONENT_COUNT}, ` +
      `got ${EOTF_ITEM_COMPONENTS.size}`,
    );
  }
  if (EOTF_SKILL_COMPONENTS.size !== EOTF_SKILL_COMPONENT_COUNT) {
    throw new Error(
      `EotF skill component contract count drift: expected ${EOTF_SKILL_COMPONENT_COUNT}, ` +
      `got ${EOTF_SKILL_COMPONENTS.size}`,
    );
  }
}
